def score(answers: list[str]) -> str:
    """answers = list of result-type tags collected across all questions."""
    counts = Counter(answers)
    top_count = counts.most_common(1)[0][1]
    winners = [tag for tag, n in counts.items() if n == top_count]
    return random.choice(winners)
